#!/usr/bin/env node
'use strict';

// Regenerates src/main/hosts-data.js from a pinned upstream commit.
//
// The hosts block is the one thing this app writes into a system file with
// elevated rights. It used to be downloaded from a moving branch at connect
// time, with no commit, tag or checksum: whatever `main` happened to return was
// written as root (#54). Worse, it changed under us — upstream deleted the
// ~2800 Discord voice entries on 2026-08-15, so the block the app advertised as
// "Discord голос, все регионы" silently stopped containing any.
//
// So the data is checked in, and updating it is a deliberate act with a
// reviewable diff:
//
//   npm run sync:hosts -- <commit>
//
// Run without an argument it re-fetches the currently pinned commit and fails if
// the bytes no longer match — which would mean the pin is not a pin.

const crypto = require('crypto');
const fs = require('fs');
const https = require('https');
const path = require('path');

const REPO = 'Flowseal/zapret-discord-youtube';
const SOURCE_PATH = '.service/hosts';

const repoRoot = path.join(__dirname, '..');
const outputPath = path.join(repoRoot, 'src', 'main', 'hosts-data.js');

function currentPin() {
  try {
    return require(outputPath).HOSTS_SOURCE_COMMIT;
  } catch (e) {
    return null;
  }
}

function fetch(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': 'unblock-pro-sync' } }, (res) => {
      if (res.statusCode !== 200) {
        reject(new Error(`HTTP ${res.statusCode} for ${url}`));
        return;
      }
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks)));
    }).on('error', reject);
  });
}

// A hosts payload we would write as root has to be exactly that and nothing
// else: address plus hostnames, comments, blank lines. Anything unexpected
// stops the sync rather than ending up in a release.
function validateHostsPayload(text) {
  const problems = [];
  const lines = String(text).split(/\r?\n/);

  lines.forEach((raw, index) => {
    const line = raw.trim();
    if (line.length === 0 || line.startsWith('#')) return;

    const fields = line.split(/\s+/);
    if (fields.length < 2) {
      problems.push(`строка ${index + 1}: нет имени хоста — ${JSON.stringify(raw)}`);
      return;
    }

    const [address, ...hostnames] = fields;
    const isIpv4 = /^\d{1,3}(\.\d{1,3}){3}$/.test(address);
    const isIpv6 = /^[0-9a-f:]+$/i.test(address) && address.includes(':');
    if (!isIpv4 && !isIpv6) {
      problems.push(`строка ${index + 1}: не похоже на адрес — ${JSON.stringify(address)}`);
    }
    for (const hostname of hostnames) {
      if (!/^[a-z0-9._-]+$/i.test(hostname)) {
        problems.push(`строка ${index + 1}: подозрительное имя — ${JSON.stringify(hostname)}`);
      }
    }
  });

  return problems;
}

function render({ commit, sha256, text }) {
  const lines = text.replace(/\r\n/g, '\n').replace(/\n*$/, '').split('\n');
  const body = lines.map((line) => '  ' + JSON.stringify(line)).join(',\n');

  return `'use strict';

// GENERATED by scripts/sync-hosts-data.js — do not edit by hand.
//
// The hosts block this app writes with elevated rights, pinned to one upstream
// commit and shipped with the release. It is not downloaded at run time: that
// download came from a moving branch with no integrity check, and it is the
// only privileged write the app performs (#54).
//
// Update deliberately, with a diff to review:
//   npm run sync:hosts -- <commit>

const HOSTS_SOURCE_REPO = ${JSON.stringify(REPO)};
const HOSTS_SOURCE_PATH = ${JSON.stringify(SOURCE_PATH)};
const HOSTS_SOURCE_COMMIT = ${JSON.stringify(commit)};
const HOSTS_SOURCE_URL =
  \`https://raw.githubusercontent.com/\${HOSTS_SOURCE_REPO}/\${HOSTS_SOURCE_COMMIT}/\${HOSTS_SOURCE_PATH}\`;

// SHA-256 of HOSTS_DATA exactly as written below, so the checked-in copy can be
// proved to be the pinned upstream bytes.
const HOSTS_DATA_SHA256 = ${JSON.stringify(sha256)};

const HOSTS_DATA = [
${body}
].join('\\n');

module.exports = {
  HOSTS_DATA,
  HOSTS_DATA_SHA256,
  HOSTS_SOURCE_COMMIT,
  HOSTS_SOURCE_PATH,
  HOSTS_SOURCE_REPO,
  HOSTS_SOURCE_URL
};
`;
}

async function main() {
  const requested = process.argv[2];
  const pinned = currentPin();
  const commit = requested || pinned;

  if (!commit) {
    console.error('Укажите коммит: npm run sync:hosts -- <commit>');
    process.exit(1);
  }
  if (!/^[0-9a-f]{40}$/.test(commit)) {
    console.error(`Нужен полный 40-символьный коммит, получено: ${commit}`);
    process.exit(1);
  }

  const url = `https://raw.githubusercontent.com/${REPO}/${commit}/${SOURCE_PATH}`;
  const buffer = await fetch(url);
  const text = buffer.toString('utf8');

  const problems = validateHostsPayload(text);
  if (problems.length > 0) {
    console.error('Содержимое не похоже на hosts — синхронизация отменена:');
    for (const problem of problems.slice(0, 20)) console.error('  ' + problem);
    process.exit(1);
  }

  const normalised = text.replace(/\r\n/g, '\n').replace(/\n*$/, '');
  const sha256 = crypto.createHash('sha256').update(normalised, 'utf8').digest('hex');

  if (!requested && pinned === commit) {
    const existing = require(outputPath);
    if (existing.HOSTS_DATA !== normalised) {
      console.error('Закреплённый коммит отдаёт другие байты, чем лежит в репозитории.');
      console.error('Это значит, что закрепление не работает — разберитесь до релиза.');
      process.exit(1);
    }
    console.log(`Закрепление на месте: ${commit} совпадает байт в байт.`);
    return;
  }

  fs.writeFileSync(outputPath, render({ commit, sha256, text: normalised }), 'utf8');
  const lineCount = normalised.split('\n').filter((l) => l.trim() && !l.trim().startsWith('#')).length;
  console.log(`Записано ${path.relative(repoRoot, outputPath)}`);
  console.log(`  коммит: ${commit}`);
  console.log(`  строк:  ${lineCount}`);
  console.log(`  sha256: ${sha256}`);
  if (pinned && pinned !== commit) console.log(`  было:   ${pinned}`);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}

module.exports = { validateHostsPayload };
